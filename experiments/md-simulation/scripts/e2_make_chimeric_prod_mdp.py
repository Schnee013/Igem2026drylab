#!/usr/bin/env python3
"""Create a chimeric production MDP from CHARMM-GUI step7 settings."""
from __future__ import annotations

import argparse
import re
import sys
import zlib
from pathlib import Path


ASSIGNMENT = re.compile(r"^(\s*[\w-]+)(\s*=\s*)(.*?)(\s*(?:;.*)?)$")


def normalize_key(key: str) -> str:
    return key.strip().lower().replace("_", "-")


def deterministic_seed(system: str, rep: int, length_ns: float) -> int:
    raw = f"{system}:rep{rep}:{length_ns:.6f}".encode("utf-8")
    return (zlib.crc32(raw) & 0x7FFFFFFF) or 1


def steps_for_interval(interval_ps: float, dt_ps: float) -> int:
    steps = int(round(interval_ps / dt_ps))
    return max(1, steps)


def patch_mdp(text: str, updates: dict[str, str]) -> str:
    seen: set[str] = set()
    out: list[str] = []
    for line in text.splitlines():
        match = ASSIGNMENT.match(line)
        if not match:
            out.append(line)
            continue
        key, sep, _value, suffix = match.groups()
        norm = normalize_key(key)
        if norm in updates:
            out.append(f"{key}{sep}{updates[norm]}{suffix}")
            seen.add(norm)
        else:
            out.append(line)

    missing = [key for key in updates if key not in seen]
    if missing:
        out.append("")
        out.append("; E2 chimeric production overrides")
        for key in missing:
            out.append(f"{key:<24}= {updates[key]}")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("system", help="System directory name under experiments/md-simulation/systems")
    parser.add_argument("rep", type=int, help="Replicate number")
    parser.add_argument("length_ns", type=float, help="Production length in ns")
    parser.add_argument("--template", type=Path, help="Input MDP template")
    parser.add_argument("--output", type=Path, default=Path("-"), help="Output MDP path, or '-' for stdout")
    parser.add_argument("--dt", type=float, default=0.002, help="Timestep in ps")
    parser.add_argument("--xtc-every-ps", type=float, default=100.0, help="Compressed XTC cadence in ps")
    parser.add_argument("--log-every-ps", type=float, default=100.0, help="Log and energy output cadence in ps")
    parser.add_argument("--seed", type=int, help="Override generated gen-seed/ld-seed")
    args = parser.parse_args()

    template = args.template or Path("experiments/md-simulation/systems") / args.system / "gromacs" / "step7_production.mdp"
    if not template.is_file():
        parser.error(f"template MDP not found: {template}")
    if args.length_ns <= 0:
        parser.error("length_ns must be positive")
    if args.dt <= 0:
        parser.error("--dt must be positive")

    nsteps = int(round(args.length_ns * 1000.0 / args.dt))
    seed = args.seed if args.seed is not None else deterministic_seed(args.system, args.rep, args.length_ns)
    cadence = steps_for_interval(args.log_every_ps, args.dt)
    xtc_cadence = steps_for_interval(args.xtc_every_ps, args.dt)

    updates = {
        "dt": f"{args.dt:.3f}",
        "nsteps": str(nsteps),
        "nstxout-compressed": str(xtc_cadence),
        "nstenergy": str(cadence),
        "nstlog": str(cadence),
        "compressed-x-grps": "SOLU",
        "continuation": "no",
        "gen-vel": "yes",
        "gen-temp": "303.15",
        "gen-seed": str(seed),
        "ld-seed": str(seed),
    }

    header = (
        f"; Generated by e2_make_chimeric_prod_mdp.py for {args.system} rep{args.rep}\n"
        f"; length_ns = {args.length_ns:g}; dt = {args.dt:g} ps; nsteps = {nsteps}\n"
        f"; protein-only XTC: compressed-x-grps = SOLU\n"
    )
    patched = header + patch_mdp(template.read_text(encoding="utf-8"), updates)

    if args.output == Path("-"):
        sys.stdout.write(patched)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(patched, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
