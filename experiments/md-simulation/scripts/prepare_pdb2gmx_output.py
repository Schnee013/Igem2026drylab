#!/usr/bin/env python3
"""Convert pdb2gmx topol.top to CHARMM-GUI-compatible PROA.itp.

4 conversion steps:
  1. Extract protein itp section from topol.top
  2. Rename moleculetype: Protein_chain_A -> PROA
  3. Generate CHARMM-GUI format position restraints (POSRES_FC_BB/POSRES_FC_SC macros)
  4. Add compatibility header

Dependencies: none (pure Python 3)
Usage: python3 prepare_pdb2gmx_output.py --topol topol.top --output-itp PROA.itp
"""

import argparse
import re
import sys

# Backbone atom names — matches CHARMM-GUI posres classification
BB_ATOMS = {"N", "CA", "C", "O"}


def parse_topol(topol_path):
    """Extract protein topology from pdb2gmx topol.top.

    Returns (lines, atoms) where atoms is [(nr, name, charge, mass), ...].
    Stops at [ system ] / [ molecules ] sections.
    Skips all #include / #ifdef / #endif directives.
    """
    lines = []
    atoms = []
    collecting = False
    in_atoms = False

    with open(topol_path) as f:
        for raw_line in f:
            stripped = raw_line.strip()

            # Detect section headers
            m = re.match(r"\[\s*(\w+)\s*\]", stripped)
            if m:
                sect = m.group(1)
                if sect == "moleculetype" and not collecting:
                    collecting = True
                elif sect in ("system", "molecules", "position_restraints"):
                    # Stop before pdb2gmx's own posres (we generate ours)
                    break
                in_atoms = (sect == "atoms") if collecting else False

            if not collecting:
                continue

            # Skip preprocessor directives (posre include, ifdef, etc.)
            if stripped.startswith("#"):
                continue

            lines.append(raw_line)

            # Parse [ atoms ] entries for posres generation + charge audit
            if in_atoms and stripped and not stripped.startswith(";") and not stripped.startswith("["):
                parts = stripped.split()
                if len(parts) >= 8:
                    try:
                        nr = int(parts[0])
                        name = parts[4]
                        charge = float(parts[6])
                        mass = float(parts[7])
                        atoms.append((nr, name, charge, mass))
                    except (ValueError, IndexError):
                        pass

    # Trim trailing blank/comment lines before appending posres
    while lines and (not lines[-1].strip() or lines[-1].strip().startswith(";")):
        lines.pop()
    lines.append("\n")

    return lines, atoms


def generate_posres(atoms):
    """Generate CHARMM-GUI format position restraints.

    BB atoms (N, CA, C, O): POSRES_FC_BB
    SC atoms (all other heavy, mass >= 2.0): POSRES_FC_SC
    H atoms (mass < 2.0): skipped
    """
    posres = ["\n#ifdef POSRES\n", "[ position_restraints ]\n"]
    bb_count = sc_count = 0

    for nr, name, _charge, mass in atoms:
        if mass < 2.0:
            continue
        if name in BB_ATOMS:
            fc = "POSRES_FC_BB"
            bb_count += 1
        else:
            fc = "POSRES_FC_SC"
            sc_count += 1
        posres.append(f"{nr:5d}     1    {fc}    {fc}    {fc}   \n")

    posres.append("#endif\n")
    return posres, bb_count, sc_count


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--topol", required=True, help="pdb2gmx output topol.top")
    parser.add_argument("--output-itp", required=True, help="Output PROA.itp path")
    args = parser.parse_args()

    # Step 1: Extract protein topology
    topo_lines, atoms = parse_topol(args.topol)
    if not atoms:
        print("ERROR: no atoms found in topol.top", file=sys.stderr)
        sys.exit(1)

    print(f"  Extracted {len(topo_lines)} topology lines, {len(atoms)} atoms")

    # Step 2: Rename moleculetype -> PROA
    topo_lines = [l.replace("Protein_chain_A", "PROA") for l in topo_lines]

    # Step 3: Generate position restraints
    posres, bb_count, sc_count = generate_posres(atoms)
    print(f"  Position restraints: {bb_count + sc_count} heavy atoms ({bb_count} BB + {sc_count} SC)")

    # Step 4: Write output with header
    with open(args.output_itp, "w") as f:
        f.write(";;\n")
        f.write(";; Generated by prepare_pdb2gmx_output.py (pdb2gmx -> CHARMM-GUI format)\n")
        f.write(";;\n")
        f.write(";; GROMACS topology file for PROA\n")
        f.write(";;\n\n")
        f.writelines(topo_lines)
        f.writelines(posres)

    # Charge audit
    qtot = sum(c for _, _, c, _ in atoms)
    qtot_rounded = round(qtot)
    charge_ok = abs(qtot - qtot_rounded) < 0.01

    print(f"  Total charge: {qtot:.3f} (rounded: {qtot_rounded}, integer: {'YES' if charge_ok else 'NO'})")
    print(f"  Wrote {args.output_itp}")

    if not charge_ok:
        print(f"  WARNING: non-integer total charge ({qtot:.6f})", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
