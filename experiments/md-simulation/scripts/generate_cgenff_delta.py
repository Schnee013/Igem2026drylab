#!/usr/bin/env python
"""
Generate cgenff_ASCR18.itp — CGenFF delta force field parameters.

Strips [ defaults ] from CGenFF charmm36.itp (since forcefield.itp
already defines it), outputs the rest for #include in topol.top.

Also generates posre_ASCR18.itp (heavy-atom position restraints).

Dependencies: none (pure Python)
Usage: python generate_cgenff_delta.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]

CGENFF_ITP = ROOT / "experiments/md-simulation/parameters/ascr18/deprotonated/charmm-gui-7629292909/gromacs/charmm36.itp"
ASCR18_ITP = ROOT / "experiments/md-simulation/parameters/ascr18/deprotonated/charmm-gui-7629292909/gromacs/ASCR18.itp"

SYSTEMS = ["Gpr2_WT", "Gpr3_WT"]
N_HEAVY = 23  # atoms 1-23 in ASCR18.itp are heavy atoms


def strip_defaults(input_path):
    """Read charmm36.itp, remove [ defaults ] section, return cleaned text."""
    lines = input_path.read_text().splitlines(keepends=True)
    out = []
    skip = False
    for line in lines:
        stripped = line.strip()
        if stripped == "[ defaults ]":
            skip = True
            continue
        if skip:
            if stripped.startswith("[") and stripped != "[ defaults ]":
                skip = False
            elif stripped == "" or stripped.startswith(";"):
                continue
            else:
                continue
        if not skip:
            out.append(line)
    return "".join(out)


def generate_posre(n_heavy, fc=1000):
    """Generate position restraints for heavy atoms."""
    lines = [
        "; Position restraints for ASCR18 heavy atoms\n",
        "; Generated by generate_cgenff_delta.py\n",
        "\n",
        "[ position_restraints ]\n",
        ";  i funct       fcx        fcy        fcz\n",
    ]
    for i in range(1, n_heavy + 1):
        lines.append(f"{i:4d}    1    {fc:5d}    {fc:5d}    {fc:5d}\n")
    return "".join(lines)


def main():
    # 1. Generate cgenff_ASCR18.itp
    delta_content = strip_defaults(CGENFF_ITP)
    # Add header
    header = (
        ";;\n"
        ";; CGenFF parameters for ASCR18 (deprotonated ascr#18)\n"
        ";; Extracted from CHARMM-GUI charmm36.itp, [ defaults ] removed\n"
        ";; Include AFTER forcefield.itp in topol.top\n"
        ";;\n\n"
    )
    delta_content = header + delta_content

    # 2. Generate posre_ASCR18.itp
    posre_content = generate_posre(N_HEAVY)

    # 3. Copy ASCR18.itp
    ascr18_content = ASCR18_ITP.read_text()

    # 4. Write to each system
    for sys_name in SYSTEMS:
        sys_dir = ROOT / f"experiments/md-simulation/systems/{sys_name}/gromacs"
        toppar_dir = sys_dir / "toppar"

        # cgenff delta → toppar/
        out_cgenff = toppar_dir / "cgenff_ASCR18.itp"
        out_cgenff.write_text(delta_content)
        print(f"  Wrote {out_cgenff.relative_to(ROOT)}")

        # posre → gromacs/
        out_posre = sys_dir / "posre_ASCR18.itp"
        out_posre.write_text(posre_content)
        print(f"  Wrote {out_posre.relative_to(ROOT)}")

        # ASCR18.itp → gromacs/
        out_ascr18 = sys_dir / "ASCR18.itp"
        out_ascr18.write_text(ascr18_content)
        print(f"  Wrote {out_ascr18.relative_to(ROOT)}")

    print("\n✓ All delta files generated.")


if __name__ == "__main__":
    main()
