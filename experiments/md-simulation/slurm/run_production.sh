#!/bin/bash
#SBATCH --job-name=md_prod
#SBATCH --partition=gpu
#SBATCH --nodelist=node3
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=16
#SBATCH --gres=gpu:rtx5090:1
#SBATCH --mem=128G
#SBATCH --time=168:00:00
#SBATCH --output=prod_%j.log
#SBATCH --error=prod_%j.err

# Generic production MD script (shared by chimeric and mutant pipelines)
#
# Usage: sbatch run_production.sh <SYSTEM_DIR> <LENGTH_NS> <REPLICA> [--input <gro>] [--mdp <mdp>]
#
# Examples:
#   # Chimeric: 500 ns, replica 1 (starts from step6.6.gro)
#   sbatch run_production.sh chimeric-gpr3-aogpa2-c37 500 1
#
#   # Chimeric: 500 ns, replica 2 (different seed)
#   sbatch run_production.sh chimeric-gpr3-aogpa2-c37 500 2
#
#   # Mutant: 200 ns from step7 output
#   sbatch run_production.sh Gpr3_V138R 200 1 --input step7.gro
#
#   # Custom MDP
#   sbatch run_production.sh chimeric-gpr3-aogpa2-c37 500 1 --mdp custom_prod.mdp
#
# Output: prod_repN/ directory with trajectory files
#
# Pipeline context: chimeric-md-execution.md Phase C4

set -euo pipefail

SYSTEM=${1:?Usage: sbatch run_production.sh <SYSTEM_DIR> <LENGTH_NS> <REPLICA> [--input <gro>] [--mdp <mdp>]}
LENGTH_NS=${2:?Missing LENGTH_NS}
REPLICA=${3:?Missing REPLICA}
shift 3

# Defaults
INPUT_GRO="step6.6.gro"
MDP_FILE=""

# Parse options
while [[ $# -gt 0 ]]; do
    case "$1" in
        --input)
            INPUT_GRO="$2"
            shift 2
            ;;
        --mdp)
            MDP_FILE="$2"
            shift 2
            ;;
        *)
            echo "Unknown option: $1"
            exit 1
            ;;
    esac
done

WORK=$HOME/md-simulation/${SYSTEM}/gromacs
cd "$WORK" || exit 1

PROD_DIR="prod_rep${REPLICA}"
mkdir -p "$PROD_DIR"

echo "=== Production MD: ${SYSTEM} ==="
echo "  Length: ${LENGTH_NS} ns"
echo "  Replica: ${REPLICA}"
echo "  Input: ${INPUT_GRO}"
echo "  Output dir: ${PROD_DIR}/"
echo "  Started: $(date)"

# Load GROMACS
GMXPREFIX=/opt/softwares/spack/opt/spack/linux-zen4/gromacs-2025.2-v5xhhnf3iroo56vaxpp77aqr27xkkykx
set +u
source "${GMXPREFIX}/bin/GMXRC.bash"
set -u

if [ ! -f "$INPUT_GRO" ]; then
    echo "ERROR: $INPUT_GRO not found in $WORK"
    exit 1
fi

# Calculate nsteps: LENGTH_NS * 1e6 / 2 (2 fs timestep)
NSTEPS=$(( LENGTH_NS * 500000 ))

# Generate production MDP if not provided
if [ -z "$MDP_FILE" ]; then
    MDP_FILE="${PROD_DIR}/production.mdp"
    cat > "$MDP_FILE" << 'MDPEOF'
; Production MD — CHARMM36m + POPC membrane
; Auto-generated by run_production.sh

integrator              = md
dt                      = 0.002     ; 2 fs
NSTEPS_PLACEHOLDER

; Output control
nstxout                 = 0
nstvout                 = 0
nstfout                 = 0
nstxout-compressed      = 50000    ; 100 ps
nstlog                  = 50000
nstenergy               = 5000     ; 10 ps
compressed-x-grps       = SOLU

; Neighbor searching
cutoff-scheme           = Verlet
nstlist                 = 20
rlist                   = 1.2
vdwtype                 = Cut-off
vdw-modifier            = Force-switch
rvdw-switch             = 1.0
rvdw                    = 1.2

; Electrostatics
coulombtype             = PME
rcoulomb                = 1.2
pme-order               = 4
fourierspacing          = 0.12

; Temperature coupling
tcoupl                  = V-rescale
tc-grps                 = SOLU MEMB SOLV
tau-t                   = 1.0 1.0 1.0
ref-t                   = 303.15 303.15 303.15

; Pressure coupling (semi-isotropic for membrane)
pcoupl                  = Parrinello-Rahman
pcoupltype              = semiisotropic
tau-p                   = 5.0
ref-p                   = 1.0 1.0
compressibility         = 4.5e-5 4.5e-5

; Bond constraints
constraints             = h-bonds
constraint-algorithm    = LINCS
lincs-iter              = 1
lincs-order             = 4

; Velocity generation
gen-vel                 = yes
gen-temp                = 303.15
GENSEED_PLACEHOLDER

; PBC
pbc                     = xyz
DispCorr                = no       ; not used with Force-switch

; COM motion removal
nstcomm                 = 100
comm-mode               = linear
comm-grps               = SOLU_MEMB SOLV

; Free energy (off)
free-energy             = no
MDPEOF

    # Set nsteps and seed
    SEED=$((REPLICA * 12345 + $(date +%s) % 100000))
    sed -i "s/NSTEPS_PLACEHOLDER/nsteps                  = ${NSTEPS}/" "$MDP_FILE"
    sed -i "s/GENSEED_PLACEHOLDER/gen-seed                = ${SEED}/" "$MDP_FILE"

    echo "  MDP generated: nsteps=${NSTEPS}, seed=${SEED}"
fi

# grompp
echo ""
echo "=== grompp ==="
gmx_mpi grompp -f "$MDP_FILE" \
    -c "$INPUT_GRO" -r "$INPUT_GRO" \
    -p topol.top -n index.ndx \
    -o "${PROD_DIR}/prod.tpr" -maxwarn 2

# mdrun
echo ""
echo "=== mdrun (${LENGTH_NS} ns) ==="
cd "$PROD_DIR"
gmx_mpi mdrun -v -deffnm prod -ntomp 16 -gpu_id 0

echo ""
echo "=== Production complete: ${SYSTEM} rep${REPLICA} ==="
echo "  Trajectory: ${PROD_DIR}/prod.xtc"
echo "  Final structure: ${PROD_DIR}/prod.gro"
echo "  Finished: $(date)"
