#!/usr/bin/env python3
"""Write an AutoDock Vina config from explicit box values and Vina defaults."""

from __future__ import annotations

import argparse
import math
import os
import sys
import tempfile
from pathlib import Path
from typing import Sequence

from docking_tool_result import ToolArtifact, write_tool_result


class InputError(ValueError):
    """A command input or output path violates the CLI contract."""


class VinaArgumentParser(argparse.ArgumentParser):
    """Keep parser failures actionable and tied to concrete option names."""

    def __init__(self, *args: object, short_usage: str, **kwargs: object) -> None:
        self.short_usage = short_usage
        super().__init__(*args, **kwargs)

    def error(self, message: str) -> None:
        self.exit(
            2,
            f"Error: {message}\n"
            f"Usage: {self.short_usage}\n"
            "Use -h or --help for details.\n",
        )


def finite_float(value: str) -> float:
    try:
        parsed = float(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"must be a finite number: {value!r}") from exc
    if not math.isfinite(parsed):
        raise argparse.ArgumentTypeError(f"must be a finite number: {value!r}")
    return parsed


def positive_float(value: str) -> float:
    parsed = finite_float(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("must be > 0")
    return parsed


def positive_int(value: str) -> int:
    try:
        parsed = int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"must be a positive integer: {value!r}") from exc
    if parsed <= 0:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return parsed


def integer(value: str) -> int:
    try:
        return int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"must be an integer: {value!r}") from exc


def ensure_readable_file(path: Path, label: str) -> None:
    if not path.exists():
        raise InputError(f"{label} does not exist: {path}")
    if not path.is_file():
        raise InputError(f"{label} is not a regular file: {path}")
    try:
        with path.open("rb"):
            pass
    except OSError as exc:
        raise InputError(f"{label} is not readable: {path} ({exc})") from exc


def ensure_output_available(path: Path, force: bool) -> None:
    if path.exists() and not force:
        raise InputError(f"output already exists: {path} (use --force to overwrite)")
    if not path.parent.exists():
        raise InputError(f"output directory does not exist: {path.parent}")
    if not path.parent.is_dir():
        raise InputError(f"output parent is not a directory: {path.parent}")


def ensure_output_not_input(output: Path, inputs: Sequence[tuple[str, Path]]) -> None:
    output_resolved = output.resolve()
    for label, input_path in inputs:
        if output_resolved == input_path.resolve():
            raise InputError(f"--output must differ from {label}: {input_path}")


def atomic_write_text(path: Path, content: str, force: bool) -> None:
    ensure_output_available(path, force)
    descriptor: int | None = None
    temporary_path: Path | None = None
    try:
        descriptor, temporary_name = tempfile.mkstemp(
            prefix=f".{path.name}.", dir=path.parent
        )
        temporary_path = Path(temporary_name)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            descriptor = None
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        if force:
            os.replace(temporary_path, path)
            temporary_path = None
        else:
            try:
                os.link(temporary_path, path)
            except FileExistsError as exc:
                raise InputError(
                    f"output appeared during writing and was not overwritten: {path}"
                ) from exc
    except InputError:
        raise
    except OSError as exc:
        raise InputError(f"could not write output {path}: {exc}") from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)
        if temporary_path is not None:
            try:
                temporary_path.unlink()
            except FileNotFoundError:
                pass


def build_config(args: argparse.Namespace) -> str:
    lines = [
        "# AutoDock Vina config generated by define_vina_box.py.",
        f"receptor = {args.receptor}",
        f"ligand = {args.ligand}",
        f"center_x = {args.center_x:g}",
        f"center_y = {args.center_y:g}",
        f"center_z = {args.center_z:g}",
        f"size_x = {args.size_x:g}",
        f"size_y = {args.size_y:g}",
        f"size_z = {args.size_z:g}",
        f"exhaustiveness = {args.exhaustiveness}",
        f"num_modes = {args.num_modes}",
        f"energy_range = {args.energy_range:g}",
        f"seed = {args.seed}",
    ]
    return "\n".join(lines) + "\n"


def build_parser() -> VinaArgumentParser:
    template = (
        "define_vina_box.py --receptor <receptor.pdbqt> --ligand <ligand.pdbqt> "
        "--center-x <angstrom> --center-y <angstrom> --center-z <angstrom> "
        "--size-x <angstrom> --size-y <angstrom> --size-z <angstrom> "
        "--output <config.txt> [--exhaustiveness <int>] [--num-modes <int>] "
        "[--energy-range <kcal/mol>] [--seed <int>] [--force]"
    )
    parser = VinaArgumentParser(
        short_usage=template,
        add_help=False,
        description=(
            "Create one AutoDock Vina config file. The box center and box size "
            "are required. Run parameters default to AutoDock Vina 1.2.7 CLI "
            "defaults and can be overridden explicitly."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Units and defaults:\n"
            "  center_* and size_* are Angstrom values written directly to the config.\n"
            "  energy_range is written in kcal/mol as expected by Vina.\n"
            "  Vina 1.2.7 defaults: exhaustiveness=8, num_modes=9, energy_range=3, seed=0.\n\n"
            "Call template:\n"
            f"  {template}"
        ),
    )
    required = parser.add_argument_group("required arguments")
    required.add_argument("--receptor", required=True, type=Path, help="readable receptor PDBQT")
    required.add_argument("--ligand", required=True, type=Path, help="readable ligand PDBQT")
    required.add_argument("--center-x", required=True, type=finite_float, help="box center X in Angstrom")
    required.add_argument("--center-y", required=True, type=finite_float, help="box center Y in Angstrom")
    required.add_argument("--center-z", required=True, type=finite_float, help="box center Z in Angstrom")
    required.add_argument("--size-x", required=True, type=positive_float, help="box size X in Angstrom")
    required.add_argument("--size-y", required=True, type=positive_float, help="box size Y in Angstrom")
    required.add_argument("--size-z", required=True, type=positive_float, help="box size Z in Angstrom")
    required.add_argument("--output", required=True, type=Path, help="output Vina config path")
    optional = parser.add_argument_group("optional arguments")
    optional.add_argument("--exhaustiveness", default=8, type=positive_int, help="Vina exhaustiveness; default: 8")
    optional.add_argument("--num-modes", default=9, type=positive_int, help="Vina num_modes; default: 9")
    optional.add_argument("--energy-range", default=3.0, type=positive_float, help="Vina energy_range in kcal/mol; default: 3")
    optional.add_argument("--seed", default=0, type=integer, help="Vina random seed; default: 0")
    optional.add_argument("--force", action="store_true", help="overwrite an existing output")
    optional.add_argument("-h", "--help", action="help", help="show this help and exit")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    args.receptor = args.receptor.expanduser()
    args.ligand = args.ligand.expanduser()
    args.output = args.output.expanduser()
    try:
        ensure_output_available(args.output, args.force)
        ensure_readable_file(args.receptor, "--receptor")
        ensure_readable_file(args.ligand, "--ligand")
        ensure_output_not_input(
            args.output,
            (("--receptor", args.receptor), ("--ligand", args.ligand)),
        )
        atomic_write_text(args.output, build_config(args), args.force)
    except InputError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    print(f"Wrote {args.output}")
    write_tool_result([ToolArtifact(args.output, "Vina 配置")])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
